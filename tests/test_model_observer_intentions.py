"""The model observer only executes admitted local bytes and fixed operators."""
import json
from pathlib import Path

from vld import ObserverIntention
from experiments.model_fabric.byte_lm import fit_byte_lm
from experiments.model_fabric.tiny_attention import deterministic_local_neural_weights
from experiments.observer_intent.arbitrate import arbitrate,render_result


def test_external_observer_can_execute_trained_language_ground(tmp_path):
    ground=fit_byte_lm(b"abab"*200)
    (tmp_path/"lm.json").write_text(json.dumps(ground))
    req=ObserverIntention(
        "model.byte.generate","workspace:lm.json",output="json",
        options={"prompt_hex":b"a".hex(),"steps":8})
    receipt=arbitrate(req,byte_root=tmp_path)
    assert receipt["status"]=="MODELED_WEIGHT_BACKED_INFERENCE"
    assert bytes.fromhex(receipt["result"]["generated_hex"])==b"babababa"
    assert receipt["plan"]["authority"]==(
        "read_only_model_evaluation_no_remote_inference_or_code_loading")
    assert json.loads(render_result(receipt,"json"))["status"]==receipt["status"]
    assert "Generated bytes:" in render_result(receipt,"text")


def test_byte_model_prediction_intention_uses_actual_admitted_sparse_weights(tmp_path):
    (tmp_path/"lm.json").write_text(json.dumps(fit_byte_lm(b"abab"*200)))
    req=ObserverIntention(
        "model.byte.predict","workspace:lm.json",
        options={"previous_byte":ord("a"),"limit":3})
    receipt=arbitrate(req,byte_root=tmp_path)
    assert receipt["status"]=="MODELED_WEIGHT_BACKED_INFERENCE"
    assert receipt["result"]["ranked_tokens"][0]["byte"]==ord("b")
    assert len(receipt["result"]["ranked_tokens"])==3


def test_external_observer_runs_tiny_attention_only_when_real_f32_bytes_exist(tmp_path):
    actual=deterministic_local_neural_weights()
    (tmp_path/"weights.safetensors").write_bytes(actual)
    req=ObserverIntention(
        "model.neural.generate","workspace:weights.safetensors",output="json",
        options={"input_tokens":[0,1,2],"steps":5})
    result=arbitrate(req,byte_root=tmp_path)
    assert result["status"]=="ACTUAL_LOCAL_WEIGHT_BACKED_NEURAL_INFERENCE"
    assert len(result["result"]["generated_tokens"])==5
    assert len(result["result"]["step_receipt_digests"])==5
    assert result["result"]["scope"].startswith("untrained_small_model")
    assert len(render_result(result,"jsonl").splitlines())==1


def test_remote_model_execution_and_incomplete_or_bad_weights_are_refused(tmp_path):
    request=ObserverIntention(
        "model.neural.generate",
        "https://huggingface.co/anonymous/whatever/resolve/main/model.safetensors",
        options={"input_tokens":[0],"steps":1})
    receipt=arbitrate(request,byte_root=tmp_path)
    assert receipt["status"]=="REFUSED"
    assert receipt["reason"]=="LOCAL_WEIGHT_ARTIFACT_REQUIRED"
    (tmp_path/"incomplete.safetensors").write_bytes(b"\x02"*10)
    request=ObserverIntention(
        "model.neural.generate","workspace:incomplete.safetensors",
        options={"input_tokens":[0],"steps":1})
    assert arbitrate(request,byte_root=tmp_path)["status"]=="UNRESOLVED"
    (tmp_path/"ok.safetensors").write_bytes(deterministic_local_neural_weights())
    invalid=ObserverIntention(
        "model.neural.generate","workspace:ok.safetensors",
        options={"input_tokens":[256],"steps":1})
    assert arbitrate(invalid,byte_root=tmp_path)["status"]=="UNRESOLVED"
