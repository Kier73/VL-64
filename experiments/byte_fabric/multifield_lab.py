"""Controlled multi-variable Ground experiment on exact VL-64 software bytes.

The constant byte context is an actual source excerpt. State transitions are
generated by an independently defined reference machine. This exercises
multi-span Ground learning; it does not imply VL-64 source is changing.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import time
from pathlib import Path

from vld import ObserverIntention

from .multifield_ground import discover_multifield_ground,MultiFieldNavigator

FRAME_SIZE=512
MODE_AT=73
COUNTER_AT=311


def source_template():
    original=Path("src/vld/__init__.py").read_bytes()
    if len(original)<FRAME_SIZE:
        raise ValueError("Cannot construct exact reference byte template")
    return original[:FRAME_SIZE]


def frame(template,mode,count):
    raw=bytearray(template)
    raw[MODE_AT]=mode
    raw[COUNTER_AT:COUNTER_AT+2]=bytes([count,255-count])
    return bytes(raw)


def reference_transition(mode,count,action):
    if action=="tick":
        return mode,(count+(1 if mode==0 else 2))%4
    if action=="toggle":
        return 1-mode,count
    raise ValueError("Unknown independent reference action")


def observed_edges(template,omit=()):
    frames=[]
    for mode in (0,1):
        for counter in range(4):
            for action in ("tick","toggle"):
                if (mode,counter,action) in omit:
                    continue
                after=reference_transition(mode,counter,action)
                frames.append((frame(template,mode,counter),action,
                               frame(template,*after)))
    return frames


def experiment():
    template=source_template()
    train=observed_edges(template)
    # Independent reference generation, not a predicted transition table.
    heldout=list(observed_edges(template))
    started=time.perf_counter_ns()
    learned=discover_multifield_ground(train,heldout)
    fit_ms=(time.perf_counter_ns()-started)/1e6
    ground=learned["ground"]
    nav=MultiFieldNavigator(ground)
    before=frame(template,1,2)
    observe=nav.observe_partial(before,[(0,16),(73,74)])
    if observe["status"]!="MULTIPLE_COMPATIBLE_MODEL_STATES":
        raise RuntimeError("Partial byte evidence was treated as complete")
    suggestion=observe["next_probe"]
    if suggestion["byte_interval"]!=[311,313]:
        raise RuntimeError("Ground did not identify missing counter bytes")
    horizon=10**12+3
    initial=bytes([0,0,255]).hex()
    far=nav.navigate(initial,"tick",horizon,"bytes.snapshot",include_data=True)
    expected=frame(template,0,horizon%4)
    if (far["status"]!="OBSERVED_GROUND_NAVIGATION" or
            base64.b64decode(far["result"]["data_b64"])!=expected):
        raise RuntimeError("Long-horizon modeled byte snapshot disagrees")
    changed=bytearray(heldout[0][2])
    changed[20] ^= 1
    challenge=nav.challenge([(heldout[0][0],heldout[0][1],bytes(changed))])
    if challenge["status"]!="CONTRADICTED":
        raise RuntimeError("Changed byte was not rejected")
    partial=discover_multifield_ground(
        observed_edges(template,omit=((1,3,"tick"),)),
        [(frame(template,1,3),"tick",frame(template,1,1))])
    unknown=MultiFieldNavigator(partial["ground"]).navigate(
        bytes([1,3,252]).hex(),"tick",10**12)
    if unknown["status"]!="UNRESOLVED" or unknown["completed_steps"]!=0:
        raise RuntimeError("Missing transition incorrectly used for navigation")
    report={
        "schema":"vl64.multifield-ground-experiment.v1",
        "status":"HELDOUT_MULTI_FIELD_GROUND_VALIDATED",
        "reference_context":"actual_source_bytes_plus_controlled_independent_state_transition",
        "source_excerpt_sha256":hashlib.sha256(template).hexdigest(),
        "frame_bytes":len(template),
        "training_edges":len(train),"heldout_edges":len(heldout),
        "changing_byte_spans":ground["variable_spans"],
        "state_count":learned["measurement"]["states"],
        "action_count":learned["measurement"]["actions"],
        "known_transition_edges":learned["measurement"]["observed_edges"],
        "description_bytes":learned["measurement"]["description_bytes"],
        "raw_transition_frame_bytes":learned["measurement"]["raw_transition_frame_bytes"],
        "compression_ratio":learned["measurement"]["description_ratio"],
        "verified_heldout_count":learned["measurement"]["verified_heldout_count"],
        "witnessed_cross_field_dependency":any(
            e["input_span"]==0 and e["output_span"]==1 and e["action"]=="tick"
            for e in ground["dependency_witnesses"]),
        "partial_known_byte_count":observe["known_byte_count"],
        "partial_compatible_states":len(observe["compatible_model_states"]),
        "recommended_next_byte_interval":suggestion["byte_interval"],
        "expected_information_bits":suggestion["expected_information_bits"],
        "modeled_horizon":horizon,
        "modeled_result_sha256":far["result"]["sha256"],
        "modeled_cycle_skipped_steps":far["cycle_skipped_steps"],
        "model_transitions_evaluated":far["evaluated_transitions"],
        "missing_edge_status":unknown["status"],
        "tampered_byte_status":challenge["status"],
        "discovery_ms_one_run":round(fit_ms,4),
        "scope":"synthetic_state_machine_with_real_source_template_no_global_equivalence",
        "core_modified":False,
    }
    return {"ground":ground,"report":report}


def _write(path,object):
    path.write_text(json.dumps(object,sort_keys=True,indent=2)+"\n")


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--out",default="artifacts")
    args=parser.parse_args()
    output=Path(args.out)
    output.mkdir(exist_ok=True,parents=True)
    result=experiment()
    groundpath=output/"learned-multifield-ground.json"
    _write(groundpath,result["ground"])
    _write(output/"multifield-observation-report.json",result["report"])
    navigate=ObserverIntention(
        "ground.multifield.navigate",
        "workspace:"+groundpath.as_posix(),output="json",
        options={"goal":{
            "initial_state_hex":bytes([0,0,255]).hex(),
            "action":"tick","steps":10**12+3,
            "kind":"digest.sha256",
        }})
    partial=ObserverIntention(
        "ground.multifield.observe",
        "workspace:"+groundpath.as_posix(),output="json",
        options={"goal":{
            "known_intervals":[[73,74]],
            "segments_b64":[base64.b64encode(bytes([1])).decode()],
        }})
    _write(output/"multifield-navigate-intention.json",navigate.to_dict())
    _write(output/"multifield-partial-intention.json",partial.to_dict())
    print("VL64_MULTIFIELD_REPORT "+json.dumps(result["report"],sort_keys=True))
    print("VL64_MULTIFIELD_GROUND "+json.dumps(result["ground"],sort_keys=True,
                                            separators=(",",":")))


if __name__=="__main__":
    main()
